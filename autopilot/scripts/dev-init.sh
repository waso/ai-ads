#!/usr/bin/env bash
# Creates ~/.ads-autopilot/env with fresh local secrets (login password, approval-link secret, one MCP token per loop).
# Safe to run again: it never overwrites an existing file unless you pass --force.
set -euo pipefail

HOME_DIR="${AUTOPILOT_HOME:-$HOME/.ads-autopilot}"
ENV_FILE="$HOME_DIR/env"

if [ -f "$ENV_FILE" ] && [ "${1:-}" != "--force" ]; then
  echo "$ENV_FILE already exists (use --force to replace it)."
  exit 0
fi

command -v openssl >/dev/null || { echo "openssl is required to generate secrets" >&2; exit 1; }
mkdir -p "$HOME_DIR"
chmod 700 "$HOME_DIR"

owner="${OWNER_EMAIL:-$(git config --global user.email 2>/dev/null || true)}"
owner="${owner:-owner@local.test}"
secret() { openssl rand -hex 32; }

umask 077
cat > "$ENV_FILE" <<ENV
# Local settings for the Ads Autopilot. Generated by scripts/dev-init.sh. Keep this file private (mode 600).
# Everything here can be overridden by editing the line or exporting the variable before scripts/dev-start.sh.

OWNER_EMAIL=$owner
DEV_LOGIN_PASSWORD=$(secret)
APPROVAL_LINK_SECRET=$(secret)

# One token per Claude loop. A token can only start and use runs of its own loop.
MCP_TOKEN_TRIAGE=$(secret)
MCP_TOKEN_DAILY=$(secret)
MCP_TOKEN_WEEKLY=$(secret)
MCP_TOKEN_CHAT=$(secret)

# sandbox = a simulated Google Ads account (nothing is sent to Google). Switch to google only after a live test account run.
ADS_MODE=sandbox

# L0 observe, L1 propose only, L2 limited autonomy, L3 extended. Raise one step at a time.
AUTONOMY_LEVEL=L1

# Limits for roughly 500 PLN a week.
MONTHLY_CAP_MICROS=2200000000
ALLOWED_DOMAINS=vibefactory.ai
ALLOWED_GEO_TARGETS=2616

# Unit economics (account currency micros). Fill these once you know your numbers; the server then refuses a target CPA
# above break-even (lifetime value x gross margin).
# VALUE_PER_SALE_MICROS=
# LIFETIME_VALUE_MICROS=
# GROSS_MARGIN_PCT=
# TARGET_CPA_MICROS=

# Google Ads (only for ADS_MODE=google)
# ADS_DEVELOPER_TOKEN=
# ADS_CUSTOMER_ID=
# ADS_LOGIN_CUSTOMER_ID=
# GOOGLE_APPLICATION_CREDENTIALS=/path/to/service-account-key.json
ENV
chmod 600 "$ENV_FILE"

echo "Wrote $ENV_FILE"
echo "Next: scripts/dev-start.sh"
